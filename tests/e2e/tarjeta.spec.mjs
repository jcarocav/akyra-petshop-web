// Card de producto: selector de cantidad, tope, Añadir, tallas y granel.
import { abrirCard, carritoGuardado, elegirProducto, expect, formatoCLP, test } from './ayuda.mjs'

test('− y + cambian la cantidad sin bajar de 1 ni pasar el tope', async ({ page }) => {
  await page.goto('/catalogo.html')
  const p = await elegirProducto(page, 'simple-tope-chico')
  const card = await abrirCard(page, p)
  const campo = card.getByLabel(`Cantidad de ${p.nombre}`)
  const menos = card.getByRole('button', { name: `Restar uno a ${p.nombre}` })
  const mas = card.getByRole('button', { name: `Sumar uno a ${p.nombre}` })
  await expect(campo).toHaveValue('1')
  await expect(menos).toHaveAttribute('aria-disabled', 'true')
  await menos.dispatchEvent('click') // desactivado (aria-disabled): no hace nada
  await expect(campo).toHaveValue('1')
  for (let i = 1; i < p.tope; i++) await mas.click()
  await expect(campo).toHaveValue(String(p.tope))
  await expect(mas).toHaveAttribute('aria-disabled', 'true')
  await expect(card.locator('[data-aviso]')).toContainText('Máximo disponible')
  await mas.dispatchEvent('click')
  await expect(campo).toHaveValue(String(p.tope))
  // Escribir más que el tope lo ajusta al máximo
  await campo.fill('999')
  await campo.press('Enter')
  await expect(campo).toHaveValue(String(p.tope))
  await campo.fill('0')
  await campo.press('Enter')
  await expect(campo).toHaveValue('1')
  await expect(page.locator('#anuncios')).toContainText('Cantidad: 1')
})

test('"Añadir" agrega exactamente la cantidad elegida y repetir acumula', async ({ page }) => {
  await page.goto('/catalogo.html')
  const p = await elegirProducto(page, 'simple-sin-tope')
  const card = await abrirCard(page, p)
  const mas = card.getByRole('button', { name: `Sumar uno a ${p.nombre}` })
  await mas.click()
  await mas.click()
  await card.getByRole('button', { name: `Añadir ${p.nombre} al carrito` }).click()
  await expect(page.locator('#toast')).toContainText(`Agregado: 3 × ${p.nombre}`)
  await expect(page.locator('#contador-carrito')).toHaveText('3')
  await expect(page.locator('#boton-carrito')).toHaveAttribute('aria-label', 'Carrito, 3 productos')
  await expect(card.getByLabel(`Cantidad de ${p.nombre}`)).toHaveValue('1') // vuelve a 1
  expect(await carritoGuardado(page)).toEqual([{ id: p.id, talla: null, cantidad: 3 }])
  await mas.click()
  await card.getByRole('button', { name: `Añadir ${p.nombre} al carrito` }).click()
  await expect(page.locator('#contador-carrito')).toHaveText('5')
  expect(await carritoGuardado(page)).toEqual([{ id: p.id, talla: null, cantidad: 5 }])
})

test('no se puede pasar del tope sumando varias veces', async ({ page }) => {
  await page.goto('/catalogo.html')
  const p = await elegirProducto(page, 'simple-tope-chico')
  const card = await abrirCard(page, p)
  const anadir = card.getByRole('button', { name: `Añadir ${p.nombre} al carrito` })
  for (let i = 0; i <= p.tope; i++) await anadir.dispatchEvent('click')
  expect((await carritoGuardado(page))[0].cantidad).toBe(p.tope)
  await expect(card.locator('[data-aviso]')).toContainText('máximo disponible')
})

test('con tallas: no deja añadir sin elegir talla', async ({ page }) => {
  await page.goto('/catalogo.html')
  const p = await elegirProducto(page, 'tallas')
  const card = await abrirCard(page, p)
  const anadir = card.getByRole('button', { name: new RegExp(`Añadir ${p.nombre.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`) })
  await expect(anadir).toHaveAttribute('aria-disabled', 'true')
  await expect(card.locator('[data-aviso]')).toHaveText('Elige una talla para añadir.')
  await anadir.dispatchEvent('click') // desactivado hasta elegir talla
  expect(await carritoGuardado(page)).toEqual([])
  await expect(card.locator('[data-aviso]')).toHaveText('Primero elige una talla.')
  const talla = p.tallas[0]
  await card.locator('.talla', { hasText: new RegExp(`^${talla.talla}$`) }).click()
  await expect(card.locator('.talla', { hasText: new RegExp(`^${talla.talla}$`) })).toHaveAttribute('aria-pressed', 'true')
  await expect(card.locator('.precio')).toContainText(formatoCLP(talla.precio))
  await expect(anadir).toHaveAttribute('aria-disabled', 'false')
  await anadir.click()
  expect(await carritoGuardado(page)).toEqual([{ id: p.id, talla: talla.talla, cantidad: 1 }])
  await expect(page.locator('#toast')).toContainText(`(talla ${talla.talla})`)
})

test('granel: kilos escritos a mano (coma o punto), − y + de a 0,1 kg y precio en vivo', async ({ page }) => {
  await page.goto('/catalogo.html')
  const p = await elegirProducto(page, 'granel')
  const card = await abrirCard(page, p)
  const campo = card.getByLabel(`Kilos de ${p.nombre}`)
  const sumar = card.getByRole('button', { name: `Sumar 100 gramos a ${p.nombre}` })
  const restar = card.getByRole('button', { name: `Restar 100 gramos a ${p.nombre}` })
  const precio = card.locator('[data-subtotal]')
  await expect(campo).toHaveValue('0,1')
  await expect(precio).toHaveText(`0,1 kg = ${formatoCLP(p.precio * 0.1)}`)
  await expect(restar).toHaveAttribute('aria-disabled', 'true') // no baja de 0,1
  // 1,3 y 1.3 dan lo mismo
  await campo.fill('1,3')
  await campo.press('Enter')
  await expect(campo).toHaveValue('1,3')
  await expect(precio).toHaveText(`1,3 kg = ${formatoCLP(p.precio * 1.3)}`)
  await campo.fill('1.3')
  await campo.press('Enter')
  await expect(campo).toHaveValue('1,3')
  // "+" desde 1,3 da 1,4; "−" vuelve
  await sumar.click()
  await expect(campo).toHaveValue('1,4')
  await restar.click()
  await expect(campo).toHaveValue('1,3')
  // gramos: 0,250
  await campo.fill('0,250')
  await campo.press('Enter')
  await expect(campo).toHaveValue('0,25')
  // inválidos: se corrige al valor válido más cercano y se avisa
  await campo.fill('0')
  await campo.press('Enter')
  await expect(campo).toHaveValue('0,1')
  await expect(card.locator('[data-aviso]')).toContainText('mínima')
  await campo.fill('-2')
  await campo.press('Enter')
  await expect(campo).toHaveValue('0,1')
  await campo.fill('1,3')
  await campo.press('Enter')
  await campo.fill('abc')
  await campo.press('Enter')
  await expect(campo).toHaveValue('1,3')
  await expect(page.locator('#anuncios-urgentes')).toContainText('no es una cantidad válida')
  await campo.fill('0,12345')
  await campo.press('Enter')
  await expect(campo).toHaveValue('0,123')
  // más que el stock: se ajusta al tope
  await campo.fill('9999')
  await campo.press('Enter')
  const tope = p.tope ?? 50
  await expect(campo).toHaveValue(String(tope).replace('.', ','))
  await expect(card.locator('[data-aviso]')).not.toBeEmpty()
  await campo.fill('1,3')
  await campo.press('Enter')
  await card.getByRole('button', { name: `Añadir ${p.nombre} al carrito` }).click()
  await expect(page.locator('#toast')).toContainText(`Agregado: 1,3 kg × ${p.nombre}`)
  expect(await carritoGuardado(page)).toEqual([{ id: p.id, talla: null, cantidad: 1.3 }])
})

test('granel: el subtotal del carrito y el mensaje de WhatsApp calzan con kilos × precio', async ({ page, context }) => {
  await page.goto('/catalogo.html')
  const g = await elegirProducto(page, 'granel')
  await page.evaluate(g => localStorage.setItem('akyra_carrito_v2', JSON.stringify([{ id: g.id, talla: null, cantidad: 1.3 }])), g)
  await page.reload()
  await page.locator('#boton-carrito').click()
  const linea = page.locator(`#carrito-lista li[data-clave="${g.id}"]`)
  const esperado = formatoCLP(Math.round(g.precio * 1.3))
  await expect(linea.locator('.linea__subtotal')).toContainText(esperado)
  await expect(page.locator('#carrito-subtotal')).toHaveText(esperado)
  // en el carrito también se edita a mano y con − / +
  const campo = linea.getByLabel(`Kilos de ${g.nombre}`)
  await linea.getByRole('button', { name: `Sumar 100 gramos a ${g.nombre}` }).click()
  await expect(campo).toHaveValue('1,4')
  await campo.fill('2.5')
  await campo.press('Enter')
  await expect(page.locator(`#carrito-lista li[data-clave="${g.id}"]`).getByLabel(`Kilos de ${g.nombre}`)).toHaveValue(g.tope !== null && g.tope < 2.5 ? String(g.tope).replace('.', ',') : '2,5')
  const kilos = (await carritoGuardado(page))[0].cantidad
  await page.getByRole('button', { name: 'Continuar compra' }).click()
  await page.getByLabel('Nombre *').fill('Prueba')
  await page.getByLabel('Teléfono *').fill('912345678')
  await page.getByLabel('Sucursal de retiro *').selectOption('hornillas')
  await page.locator('label[for="pago-2"]').click()
  const nueva = context.waitForEvent('page')
  await page.getByRole('button', { name: 'Enviar pedido por WhatsApp' }).click()
  const url = new URL((await nueva).url())
  const texto = url.searchParams.get('text')
  expect(texto).toContain(`${String(kilos).replace('.', ',')} kg × ${formatoCLP(g.precio)}/kg = ${formatoCLP(Math.round(g.precio * kilos))}`)
})

