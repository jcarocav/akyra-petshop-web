  // El formulario abierto no se cierra ni se borra: solo avisa
  await expect(pc.locator('#dialogo-alerta')).toContainText('Este producto se actualizó desde otro dispositivo')
  await expect(pc.locator('#dialogo').getByLabel('Nombre que se muestra')).toHaveValue('Lo que Rosa está escribiendo')
  await pc.locator('#dialogo').getByRole('button', { name: 'Cancelar' }).click()
  // Precio desde el PC (edición rápida) mientras la foto se procesa
  await card(pc, 'GAT-LEON-910').getByRole('button', { name: /Precio \$1\.500/ }).click()
  await card(pc, 'GAT-LEON-910').locator('.precio__campo').fill('1.690')
  await card(pc, 'GAT-LEON-910').locator('.precio__campo').press('Enter')
  // Cada pantalla ve el cambio del otro sin refrescar
  await expect(card(pc, 'GAT-LEON-910')).toContainText('Foto nueva')
  await expect(card(pc, 'GAT-LEON-910')).not.toContainText('No se ve en la web')
