test('sin la clave el servidor no responde; con la clave sí (también desde otra dirección de la red local)', async ({ request }) => {
  expect((await request.get(`${h.origen}/`)).status()).toBe(403)
  expect((await request.get(`${h.origen}/api/estado`)).status()).toBe(403)
  expect((await request.get(`${h.origen}/?clave=otra-clave`)).status()).toBe(403)
  expect((await request.get(`${h.origen}/fotos/x.webp`)).status()).toBe(403)
  expect((await request.get(h.url())).status()).toBe(200)
  // "otro dispositivo": la IP de este equipo en la red local (como entra el celular)
  const ip = direccionesLocales()[0]?.ip
  if (ip) {
    expect((await request.get(`http://${ip}:${h.puerto}/api/estado`)).status()).toBe(403)
    const r = await request.get(`http://${ip}:${h.puerto}/api/estado?clave=${h.clave}`)
    expect(r.status()).toBe(200)
    expect((await r.json()).dispositivo).toBe('Celular')
  }
  // Solo red local: nada de direcciones de internet
  expect(esRedLocal('127.0.0.1')).toBe(true)
  expect(esRedLocal('192.168.43.20')).toBe(true)
  expect(esRedLocal('172.20.1.5')).toBe(true)
  expect(esRedLocal('8.8.8.8')).toBe(false)
  expect(esRedLocal('200.1.2.3')).toBe(false)
})

