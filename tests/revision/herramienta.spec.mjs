  await expect(pc.locator('#presencia')).toContainText('Celular conectado')
  await expect(cel.locator('#presencia')).toContainText('PC conectado')
  // El celular abre directo en "Fotos por sacar", en una columna
  await expect(cel.locator('#vista-fotos')).toBeVisible()
  const ancho = await cel.locator('#fotos-listas .lista-fotos').first().evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)
  expect(ancho).toBe(1)
  // Rosa (PC) abre "Modificar" del Leon Pet mientras el celular le sube la foto
  await buscar(pc, 'GAT-LEON-910')
  await card(pc, 'GAT-LEON-910').getByRole('button', { name: 'Modificar' }).click()
  await pc.locator('#dialogo').getByLabel('Nombre que se muestra').fill('Lo que Rosa está escribiendo')
  const fila = cel.locator('#fotos-listas li[data-sku="GAT-LEON-910"]')
